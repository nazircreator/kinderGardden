export type IconName = keyof typeof ICONS;

export function PixelIcon({
  name,
  size = 16,
  className = '',
  style,
  dim = false,
}: {
  name: IconName;
  size?: number;
  className?: string;
  style?: CSSProperties;
  dim?: boolean;
}) {
  const grid = ICONS[name] ?? ICONS.heart;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 8 8"
      className={`pixel-icon ${className}`}
      style={{ imageRendering: 'pixelated', opacity: dim ? 0.4 : 1, ...style }}
      aria-hidden
      focusable="false"
    >
      {grid.map((row, y) =>
        row.split('').map((ch, x) =>
          ch === '.' ? null : <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={PAL[ch]} />,
        ),
      )}
    </svg>
  );
}